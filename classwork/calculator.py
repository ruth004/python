num_one = int(input("enter number"))
num_two = int(input("enter number"))
operator = input("enter number")

if operator == "+":
	answer = num_one + num_two
	print(answer)
elif operator == "-":
	answer = num_one - num_two
	print(answer)
if operator == "*":
	answer = num_one * num_two
	print(answer)
if operator == "/":
	answer = num_one / num_two
	print(answer)
